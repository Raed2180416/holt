/**
 * Static release contract and positive control.
 *
 * A release workflow is unusually easy to make green while publishing the wrong thing: a tag can
 * move between jobs, an existing asset can be clobbered after verification, a signing step can
 * warn and continue, or a command that looks like an attestation can simply not exist. This gate
 * checks the executable release graph itself and `--self-test` plants each old failure shape.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  executableRunLines,
  FEATURE_PROOF_COMMAND,
  GIT_RUNTIME_CHECK,
  jobBlocks,
  mutableGitHubInstalls,
  OMIT_OPTIONAL_PROOF,
  runsCommand,
  usesRefs,
} from './check-ci-hardening.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, '..');

const EXPECTED_ENGINES = '^22.22.2 || ^24.15.0 || >=26.0.0';
const EXPECTED_GIT_ENGINE = '>=2.45.0';
const EXPECTED_RUNTIME_DEPENDENCIES = Object.freeze({
  '@modelcontextprotocol/sdk': '1.30.0',
  'jsonc-parser': '3.3.1',
  'tuf-js': '6.0.0',
});
const EXPECTED_OPTIONAL_DEPENDENCIES = Object.freeze({ jscpd: '5.0.14' });
const FULL_SHA = /^[0-9a-f]{40}$/;

/** @typedef {{rule:string,message:string}} Problem */

const neededBy = (body, ids) => {
  const flow = /needs:\s*\[([^\]]+)\]/.exec(body)?.[1]
    ?.split(',').map((x) => x.trim().replace(/^['"]|['"]$/g, '')) ?? [];
  return ids.every((id) => flow.includes(id));
};

/**
 * @param {{action:string, actionBuildScript:string, actionBundle:string, actionNotices:string,
 *          workflow:string, packageJson:string, lock:string, shrinkwrap:string,
 *          runtimeScript:string, supplyChain:string, alternateReleaseWorkflows?:Record<string,string>}} input
 * @returns {Problem[]}
 */
export function releaseContractProblems(input) {
  const p = [];
  const add = (rule, message) => p.push({ rule, message });
  const action = String(input.action ?? '');
  const actionBuildScript = String(input.actionBuildScript ?? '');
  const actionBundle = String(input.actionBundle ?? '');
  const actionNotices = String(input.actionNotices ?? '');
  const workflow = String(input.workflow ?? '');
  const runtimeScript = String(input.runtimeScript ?? '');
  const alternateReleaseWorkflows = input.alternateReleaseWorkflows ?? {};
  let pkg = {};
  try { pkg = JSON.parse(input.packageJson); } catch { add('package', 'package.json is not valid JSON'); }

  if (!/^\s*using:\s*['"]?node24['"]?\s*$/m.test(action)
      || !/^\s*main:\s*['"]?dist\/holt-action\.mjs['"]?\s*$/m.test(action)) {
    add('action-local', 'action.yml must execute the committed dist/holt-action.mjs under GitHub\'s Node 24 runtime');
  }
  if (!actionBundle.startsWith('#!/usr/bin/env node\n// GENERATED by scripts/build-action-bundle.mjs')
      || !actionBundle.includes('// src/action-entry.mjs')) {
    add('action-local', 'the committed action bundle is missing, hand-written, or not rooted at the fixed ci entry point');
  }
  for (const identity of [
    '@modelcontextprotocol/sdk@1.30.0',
    'jsonc-parser@3.3.1',
    'tuf-js@6.0.0',
  ]) {
    if (!actionNotices.includes(identity)) {
      add('action-licences', `the action bundle notice does not identify bundled dependency ${identity}`);
    }
  }
  for (const needle of [
    "entryPoints: [ENTRY]",
    "bundle: true",
    "platform: 'node'",
    "format: 'esm'",
    "target: 'node24'",
    "mainFields: ['module', 'main']",
    "legalComments: 'eof'",
    "process.argv.includes('--check')",
    'THIRD-PARTY-NOTICES.txt',
  ]) {
    if (!actionBuildScript.includes(needle)) {
      add('action-build', `the deterministic action builder is missing: ${needle}`);
    }
  }
  if (pkg.scripts?.['action:build'] !== 'node scripts/build-action-bundle.mjs'
      || pkg.scripts?.['action:check'] !== 'node scripts/build-action-bundle.mjs --check'
      || pkg.devDependencies?.esbuild !== '0.28.1') {
    add('action-build', 'package scripts must build/check the action with exact esbuild@0.28.1');
  }
  if (mutableGitHubInstalls(action).length) {
    add('action-mutable-install', 'action.yml installs executable GitHub bytes from a mutable tag or branch');
  }
  if (executableRunLines(action).some((x) => /\b(?:npm|pnpm|yarn)\s+(?:i|install|add|global\s+add)\b/.test(x.text))) {
    add('action-bootstrap', 'the composite action bootstraps a second package instead of using its exact checked-out contents');
  }

  const jobs = new Map(jobBlocks(workflow).map((j) => [j.id, j.body]));
  for (const id of ['preflight', 'quality', 'build', 'verify', 'attest', 'publish']) {
    if (!jobs.has(id)) add('graph', `release workflow has no ${id} job`);
  }
  const preflight = jobs.get('preflight') ?? '';
  const quality = jobs.get('quality') ?? '';
  const build = jobs.get('build') ?? '';
  const verify = jobs.get('verify') ?? '';
  const attest = jobs.get('attest') ?? '';
  const publish = jobs.get('publish') ?? '';

  // The release must measure the selected executable, not inherit a Git version from a mutable
  // runner image. Quality exercises the source tree, build executes source/package audits, and
  // verify drives the installed artifact: each needs its own proof before its first Holt command.
  for (const [id, body, firstEvidence] of [
    ['quality', quality, 'npm ci'],
    ['build', build, 'node bin/holt.mjs audit'],
    ['verify', verify, 'npm install -g'],
  ]) {
    const commands = executableRunLines(body).map((line) => line.text);
    const runtimeAt = commands.findIndex((line) => line.includes(GIT_RUNTIME_CHECK));
    const evidenceAt = commands.findIndex((line) => line.includes(firstEvidence));
    if (runtimeAt === -1) {
      add('git-runtime', `${id} does not execute the Git >=2.45 / --no-lazy-fetch and inert-hooks runtime proof`);
    } else if (evidenceAt !== -1 && runtimeAt > evidenceAt) {
      add('git-runtime', `${id} executes the Git runtime proof only after ${firstEvidence}`);
    }
  }
  for (const osName of ['ubuntu-latest', 'macos-latest', 'windows-latest']) {
    if (!verify.includes(`os: ${osName}`)) {
      add('git-runtime', `installed-artifact verification does not carry the live Git runtime proof onto ${osName}`);
    }
  }
  for (const needle of [
    'noLazyFetchSupported',
    "['--no-lazy-fetch', 'version']",
    'verifyInertHooksPath',
    'positive-control hook did not run',
    'core.hooksPath=${INERT_GIT_HOOKS_PATH}',
  ]) {
    if (!runtimeScript.includes(needle)) {
      add('git-runtime', `runtime checker is missing non-vacuous evidence: ${needle}`);
    }
  }

  if (/^\s*workflow_dispatch:/m.test(workflow)) {
    add('trigger', 'manual workflow_dispatch can bind provenance to an ambient ref different from the requested release tag');
  }
  if (!preflight.includes('^refs/tags/v[0-9]+\\.[0-9]+\\.[0-9]+$')
      || !preflight.includes('releases run only for a pushed stable vX.Y.Z tag')) {
    add('trigger', 'the first job does not fail closed unless this is a pushed stable vX.Y.Z tag');
  }
  if (usesRefs(preflight).length !== 0 || runsCommand(preflight, 'node ') || runsCommand(preflight, 'npm ')) {
    add('immutable-preflight', 'the live immutability gate must run before checkout, setup actions, or repository-controlled Node/npm code');
  }
  for (const needle of [
    'HOLT_RELEASE_ADMIN_TOKEN',
    'repos/$GITHUB_REPOSITORY/immutable-releases',
    'X-GitHub-Api-Version: 2026-03-10',
    "--jq '.enabled'",
  ]) {
    if (!preflight.includes(needle)) add('immutable-preflight', `live immutable-releases API proof is missing: ${needle}`);
  }
  if (workflow.includes('HOLT_IMMUTABLE_RELEASES_ENABLED')) {
    add('immutable-preflight', 'a repository variable is not live proof that immutable releases remain enabled');
  }
  if (!publish.includes('repos/$GITHUB_REPOSITORY/immutable-releases')
      || !publish.includes("--jq '.enabled'")) {
    add('immutable-preflight', 'publication does not re-prove the live admin-readable immutable-releases setting immediately before creating the draft');
  }

  const qualityCommands = [
    'npm ci',
    'npm install --no-save --ignore-scripts --no-package-lock playwright@1.62.1',
    'npm audit --omit=dev --audit-level=moderate',
    'npm run action:check',
    'bash scripts/clone-fixtures.sh "$HOLT_REAL_REPOS"',
    FEATURE_PROOF_COMMAND,
    'node scripts/run-feature-proof.mjs --verify-publication "$RUNNER_TEMP/feature-proof.json"',
    'npm run typecheck',
    'npm run hosts:check',
    'npm run lint:paths',
    'node scripts/check-ci-hardening.mjs --self-test',
    'node scripts/check-release-contract.mjs --self-test',
    'node scripts/gen-manifest.mjs --check',
    'node bin/holt.mjs audit',
    'git diff --exit-code',
    'git status --porcelain',
  ];
  for (const command of qualityCommands) {
    if (!runsCommand(quality, command)) add('quality', `quality job does not execute: ${command}`);
  }
  const duplicateProofReruns = ['npm test', 'npm run test:mutation']
    .filter((command) => runsCommand(quality, command));
  if (duplicateProofReruns.length) {
    add('feature-proof-budget', `release quality must consume retained feature-proof evidence instead of rerunning ${duplicateProofReruns.join(' and ')}`);
  }
  const featureProofRun = quality.indexOf(`run: ${FEATURE_PROOF_COMMAND}`);
  const featureProofUpload = quality.indexOf('uses: actions/upload-artifact@');
  if (featureProofRun === -1 || featureProofUpload < featureProofRun
      || !quality.includes('if: ${{ always() }}')
      || !quality.includes('if-no-files-found: error')
      || !quality.includes('${{ runner.temp }}/feature-proof.json')
      || !quality.includes('${{ runner.temp }}/feature-proof.json.sha256')) {
    add('feature-proof', 'release quality must execute the bounded feature runner and always retain its JSON plus SHA-256 sidecar, including an invalid completed run');
  }

  const verifyCommands = executableRunLines(verify).map((line) => line.text);
  const omittedInstallAt = verifyCommands.findIndex((line) => /npm\s+install\b/.test(line)
    && /--omit=optional\b/.test(line) && /--prefix\s+"\$OPTIONAL_PREFIX"/.test(line)
    && !/(?:^|\s)-(?:g|-global)(?:\s|$)/.test(line));
  const omissionProofAt = verifyCommands.findIndex((line) => line.includes(OMIT_OPTIONAL_PROOF));
  const omittedAuditAt = verifyCommands.findIndex((line) => line.includes('node "$HOLT_BIN" audit --require-signature'));
  const omittedSmokeAt = verifyCommands.findIndex((line) => line.includes('node scripts/smoke-installed.mjs --bin "$HOLT_BIN"'));
  if (omittedInstallAt === -1 || omissionProofAt <= omittedInstallAt
      || omittedAuditAt <= omissionProofAt || omittedSmokeAt <= omissionProofAt
      || !verify.includes('OPTIONAL_PREFIX: ${{ runner.temp }}/')
      || !verify.includes('HOLT_BIN="$OPTIONAL_PREFIX/node_modules/holt/bin/holt.mjs"')
      || runsCommand(verify, 'npm install -g --omit=optional')) {
    add('omit-optional', 'release verification must use an isolated non-global prefix, prove every optional package root absent, then audit and smoke that exact installed binary');
  }

  const exactTagChecks = (body) => body.includes('TAG_SHA=$(git rev-parse "$TAG^{commit}")')
    && body.includes('HEAD_SHA=$(git rev-parse HEAD)')
    && body.includes('if [ "$TAG_SHA" != "$HEAD_SHA" ]');
  if (!exactTagChecks(quality)) add('tag-identity', 'quality does not refuse a checked-out HEAD different from the requested tag commit');
  if (!exactTagChecks(publish)) add('tag-identity', 'publish does not re-check the remote tag against the already verified commit');

  if (!/^\s*needs:\s*preflight\s*$/m.test(quality)) add('graph', 'quality is not blocked on the no-checkout live immutability preflight');
  if (!/^\s*needs:\s*quality\s*$/m.test(build)) add('graph', 'build is not transitively blocked on quality');
  if (!neededBy(verify, ['quality', 'build'])) add('graph', 'artifact verification is not blocked on exact quality evidence and the one build job');
  if (!neededBy(attest, ['quality', 'build', 'verify'])) add('graph', 'attestation is not blocked on exact quality evidence, build, and cross-platform verification');
  if (!neededBy(publish, ['quality', 'build', 'verify', 'attest'])) add('graph', 'publication is not blocked on all quality, build, verification, and attestation evidence');

  for (const [id, body] of [['preflight', preflight], ['build', build], ['attest', attest], ['publish', publish]]) {
    if (!/^\s*environment:\s*release\s*$/m.test(body)) {
      add('environment', `${id} is privileged but is not attached to the protected release environment`);
    }
  }

  const packRuns = executableRunLines(workflow).filter((x) => /\bnpm\s+pack\s+--ignore-scripts\b/.test(x.text));
  if (packRuns.length !== 1) add('asset-once', `release must build exactly one tarball once; found ${packRuns.length} npm pack executions`);
  if (executableRunLines(workflow).some((x) => /--clobber\b/.test(x.text))
      || runsCommand(publish, 'gh release upload')) {
    add('asset-once', 'release assets may not be replaced or uploaded in a second mutable pass');
  }

  for (const needle of [
    'HOLT_RELEASE_SIGNING_KEY is required',
    'createPrivateKey',
    'createPublicKey',
    'EXPECTED_RELEASE_PUBLIC_KEY_B64',
    "signature.toString('base64')",
    'MANIFEST.sha256.sig',
    'node bin/holt.mjs audit --require-signature',
  ]) {
    if (!build.includes(needle)) add('signing', `fail-closed manifest signing is missing: ${needle}`);
  }
  if (/HOLT_RELEASE_SIGNING_KEY[^\n]*(?:warning|skip)|manifest will be unsigned/i.test(workflow)) {
    add('signing', 'missing signing evidence is allowed to warn or skip instead of failing closed');
  }
  const expectedReleaseKey = /EXPECTED_RELEASE_PUBLIC_KEY_B64:\s*([A-Za-z0-9+/=]+)/.exec(workflow)?.[1];
  const keyArray = /export const RELEASE_PUBLIC_KEYS_B64\s*=\s*\[([^\]]*)\]/.exec(String(input.supplyChain ?? ''))?.[1] ?? '';
  const trustedReleaseKeys = [...keyArray.matchAll(/['"]([^'"]+)['"]/g)].map((match) => match[1]);
  if (!expectedReleaseKey || !trustedReleaseKeys.includes(expectedReleaseKey)) {
    add('signing-trust', 'the workflow signing key is not one of the public keys the installed package trusts');
  }

  if (!runsCommand(build, 'node scripts/gen-sbom.mjs')
      || !workflow.includes('holt.cdx.json') || !workflow.includes('holt.spdx.json')) {
    add('sbom', 'release does not generate and retain both checked CycloneDX and SPDX SBOMs');
  }
  if (!workflow.includes('npm-shrinkwrap.json')) {
    add('sbom', 'the published CLI does not carry the exact dependency tree its SBOM describes');
  }

  const attestUses = usesRefs(attest).filter((u) => u.ref.startsWith('actions/attest@'));
  if (attestUses.length < 2) add('attestation', 'both generic build provenance and an SBOM attestation must use actions/attest');
  for (const u of attestUses) {
    const ref = u.ref.slice(u.ref.lastIndexOf('@') + 1);
    if (!FULL_SHA.test(ref)) add('attestation', `actions/attest is mutable: ${u.ref}`);
  }
  if (!attest.includes('subject-checksums:') || !attest.includes('sbom-path:')) {
    add('attestation', 'actions/attest is not binding the checksum subjects and SBOM to the built tarball');
  }
  if (runsCommand(attest, 'gh attestation create') || workflow.includes('gh attestation create')) {
    add('attestation', '`gh attestation create` is not a real GitHub CLI command; use actions/attest');
  }
  if (!runsCommand(attest, 'gh attestation verify')) add('attestation', 'the just-created provenance is never independently verified');
  for (const needle of ['--signer-workflow', '--source-ref', '--source-digest']) {
    if (!attest.includes(needle)) add('attestation-identity', `attestation verification does not bind ${needle}`);
  }
  if (!attest.includes('--predicate-type https://cyclonedx.org/bom')) {
    add('attestation-sbom', 'the CycloneDX attestation predicate is not separately verified');
  }

  if (!runsCommand(publish, 'gh release create') || !runsCommand(publish, '--draft')) {
    add('publish-last', 'release must be created as a draft with all assets after evidence passes');
  }
  if (!runsCommand(publish, 'gh release edit "$TAG" --draft=false')) {
    add('publish-last', 'draft release is not published as the final operation');
  }
  if (!runsCommand(publish, 'gh release verify "$TAG"')) {
    add('publish-last', 'the published immutable GitHub release attestation is not verified');
  }
  if (!publish.includes('.immutable')) add('publish-last', 'publication does not fail when repository release immutability is disabled');
  if (workflow.includes('--latest')) add('release-kind', 'stable releases must let GitHub determine latest; forcing --latest makes backfills replace the current release');
  for (const needle of ["asset.state !== 'uploaded'", 'asset.digest !== digest', "createHash('sha256')"]) {
    if (!publish.includes(needle)) add('remote-assets', `draft asset verification does not prove ${needle}`);
  }
  if (!runsCommand(publish, 'gh release verify-asset "$TAG" "$ASSET"')
      || !publish.includes('ASSETS=("$TARBALL" holt.tgz SHA256SUMS')) {
    add('remote-assets', 'every published asset, including SHA256SUMS, must pass GitHub release-asset attestation verification');
  }

  if (!pkg.files?.includes?.('npm-shrinkwrap.json')) add('package', 'npm-shrinkwrap.json is not explicitly shipped');
  if (pkg.engines?.node !== EXPECTED_ENGINES) add('package', `Node engines must name the supported current majors: ${EXPECTED_ENGINES}`);
  if (pkg.engines?.git !== EXPECTED_GIT_ENGINE) add('package', `package metadata must declare Git ${EXPECTED_GIT_ENGINE}`);
  if (JSON.stringify(pkg.dependencies ?? {}) !== JSON.stringify(EXPECTED_RUNTIME_DEPENDENCIES)) {
    add('package', 'MCP, strict JSONC parsing, and authenticated TUF policy delivery must be exact required runtime dependencies');
  }
  if (JSON.stringify(pkg.optionalDependencies ?? {}) !== JSON.stringify(EXPECTED_OPTIONAL_DEPENDENCIES)) {
    add('package', 'only the deep token-clone backend may be omitted, at its reviewed exact version');
  }
  if (pkg.overrides?.['fast-uri'] !== '3.1.5' || pkg.overrides?.hono !== '4.12.34') {
    add('package', 'patched fast-uri and hono floors are not enforced without adding direct runtime dependencies');
  }
  if (String(input.lock ?? '') !== String(input.shrinkwrap ?? '')) {
    add('package', 'package-lock.json and the publishable npm-shrinkwrap.json describe different trees');
  }
  for (const [name, alternate] of Object.entries(alternateReleaseWorkflows)) {
    const text = String(alternate ?? '');
    if (/gh\s+release\s+(?:create|upload|edit)\b/.test(text)
        || /actions\/attest@/.test(text)
        || /HOLT_RELEASE_SIGNING_KEY/.test(text)) {
      add('release-path', `${name} defines a second publishing, signing, or attestation path outside the checked release-artifact workflow`);
    }
  }
  return p;
}

async function readInput(root = ROOT) {
  const read = (rel) => fs.readFile(path.join(root, rel), 'utf8');
  const [action, actionBuildScript, actionBundle, actionNotices, workflow, packageJson, lock, shrinkwrap, runtimeScript, supplyChain] = await Promise.all([
    read('action.yml'),
    read('scripts/build-action-bundle.mjs'),
    read('dist/holt-action.mjs'),
    read('dist/THIRD-PARTY-NOTICES.txt'),
    read('.github/workflows/release-artifact.yml'),
    read('package.json'),
    read('package-lock.json'),
    read('npm-shrinkwrap.json'),
    read('scripts/check-git-runtime.mjs'),
    read('src/supply-chain.mjs'),
  ]);
  const alternateReleaseWorkflows = {};
  for (const name of await fs.readdir(path.join(root, '.github', 'workflows'))) {
    if (!/^release-.*\.ya?ml$/.test(name) || name === 'release-artifact.yml') continue;
    alternateReleaseWorkflows[name] = await read(`.github/workflows/${name}`);
  }
  return { action, actionBuildScript, actionBundle, actionNotices, workflow, packageJson, lock, shrinkwrap, runtimeScript, supplyChain, alternateReleaseWorkflows };
}

